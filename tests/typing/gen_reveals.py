"""Write one ``reveal_type`` per overload of the hand-written stubs.

For every function, method, property and overload in ``audio_samples/**/*.pyi`` this writes a
function to ``tests/typing/reveals/<module>.py`` that calls it with arguments of exactly the declared
parameter types and reveals the result. ``tests/typing/check_precision.py`` runs mypy and pyright
over these files and compares every revealed type with ``tests/typing/reveals.snapshot``, so a stub
change that alters what any overload gives fails until the snapshot is updated on purpose.

    python tests/typing/gen_reveals.py           # rewrite tests/typing/reveals/
    python tests/typing/gen_reveals.py --check   # fail if they differ from the stubs

The files are only type-checked, never run.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PKG = ROOT / "audio_samples"
OUT = ROOT / "tests" / "typing" / "reveals"

#: Class-scoped type variables of generic classes, replaced by a function-scoped one: a covariant
#: type variable cannot annotate a parameter.
CLASS_TYPEVARS = {"AudioSamples": ("_S_co", "AudioSamples[_T]")}

HEADER = '''\
# Generated by tests/typing/gen_reveals.py from {stub}. Do not edit: regenerate.
# Type-checked by mypy and pyright (tests/hooks/check_stubs.sh); never run.
# ruff: noqa
# mypy: disable-error-code="no-untyped-def"
from __future__ import annotations

from typing import Any, TypeVar
from typing_extensions import reveal_type

import numpy as np

'''


def module_name(path: Path) -> str:
    rel = path.relative_to(ROOT).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def absolute_import(node: ast.ImportFrom, mod: str, is_pkg: bool) -> ast.ImportFrom:
    if not node.level:
        return node
    base = mod.split(".") if is_pkg else mod.split(".")[:-1]
    base = base[: len(base) - (node.level - 1)]
    target = ".".join(base + ([node.module] if node.module else []))
    return ast.ImportFrom(module=target, names=node.names, level=0)


class Renamer(ast.NodeTransformer):
    """Replace names in an annotation (class type variables, ``Self``)."""

    def __init__(self, mapping: dict[str, str]):
        self.mapping = mapping

    def visit_Name(self, node: ast.Name) -> ast.AST:
        if node.id in self.mapping:
            return ast.parse(self.mapping[node.id], mode="eval").body
        return node


def ann(node: ast.expr | None, mapping: dict[str, str]) -> str:
    if node is None:
        return "Any"
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        node = ast.parse(node.value, mode="eval").body
    return ast.unparse(Renamer(mapping).visit(ast.parse(ast.unparse(node), mode="eval").body))


def decorators(fn: ast.FunctionDef) -> set[str]:
    out = set()
    for d in fn.decorator_list:
        if isinstance(d, ast.Name):
            out.add(d.id)
        elif isinstance(d, ast.Attribute):
            out.add(d.attr)
    return out


def call_and_params(fn: ast.FunctionDef, mapping: dict[str, str], skip_first: bool):
    a = fn.args
    params, args = [], []
    positional = a.posonlyargs + a.args
    if skip_first:
        positional = positional[1:]
    for p in positional:
        params.append(f"{p.arg}: {ann(p.annotation, mapping)}")
        args.append(p.arg)
    if a.vararg:
        params.append(f"*{a.vararg.arg}: {ann(a.vararg.annotation, mapping)}")
        args.append(f"*{a.vararg.arg}")
    for p in a.kwonlyargs:
        if not a.vararg and not any(x.startswith("*") for x in params):
            params.append("*")
        params.append(f"{p.arg}: {ann(p.annotation, mapping)}")
        args.append(f"{p.arg}={p.arg}")
    if a.kwarg:
        params.append(f"**{a.kwarg.arg}: {ann(a.kwarg.annotation, mapping)}")
        args.append(f"**{a.kwarg.arg}")
    return params, args


def emit_function(lines: list[str], tag: str, target: str, fn: ast.FunctionDef, mapping, self_param=None, owner=None):
    decs = decorators(fn)
    if "property" in decs:
        lines.append(f"def {tag}(self_: {self_param}) -> None:")
        lines.append(f"    reveal_type(self_.{fn.name})")
        return
    if any(d.endswith("setter") or d.endswith("deleter") for d in decs) or fn.name in ("__init__", "__new__"):
        return
    static = "staticmethod" in decs
    cls = "classmethod" in decs
    is_method = owner is not None
    params, args = call_and_params(fn, mapping, skip_first=is_method and not static)
    head = []
    callee = target
    if is_method and not static and not cls:
        first = (fn.args.posonlyargs + fn.args.args)[0]
        stype = ann(first.annotation, mapping) if first.annotation is not None else self_param
        head = [f"self_: {stype}"]
        callee = f"self_.{fn.name}"
    elif is_method:
        callee = f"{owner}.{fn.name}"
    sig = ", ".join(head + params)
    lines.append(f"def {tag}({sig}) -> None:")
    lines.append(f"    reveal_type({callee}({', '.join(args)}))")


def generate(stub: Path) -> str | None:
    mod = module_name(stub)
    is_pkg = stub.name == "__init__.pyi"
    tree = ast.parse(stub.read_text())
    imports, defined = [], []
    for node in tree.body:
        if isinstance(node, ast.Import):
            imports.append(ast.unparse(node))
        elif isinstance(node, ast.ImportFrom):
            if node.module == "__future__":
                continue
            imports.append(ast.unparse(absolute_import(node, mod, is_pkg)))
        elif isinstance(node, (ast.ClassDef, ast.FunctionDef)):
            defined.append(node.name)
        elif isinstance(node, ast.Assign):
            defined += [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            defined.append(node.target.id)
    body: list[str] = []
    seen: dict[str, int] = {}

    def tag(name: str) -> str:
        # Stable names: the n-th overload of Class.method is r_Class__method__n.
        seen[name] = seen.get(name, 0) + 1
        return f"r_{name}__{seen[name]}"

    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            body.append("")
            emit_function(body, tag(node.name), f"{node.name}", node, {})
        elif isinstance(node, ast.ClassDef):
            tv = CLASS_TYPEVARS.get(node.name)
            mapping = {}
            self_param = node.name
            if tv:
                mapping = {tv[0]: "_T", "Self": tv[1]}
                self_param = tv[1]
            else:
                mapping = {"Self": node.name}
            for item in node.body:
                if isinstance(item, ast.FunctionDef):
                    body.append("")
                    emit_function(body, tag(f"{node.name}__{item.name}"), node.name, item, mapping, self_param, node.name)
    body = [b for b in body]
    if not any(b.startswith("def ") for b in body):
        return None
    names = sorted(n for n in set(defined) if not (n.startswith('__') and n.endswith('__')))
    text = HEADER.format(stub=stub.relative_to(ROOT).as_posix())
    text += "\n".join(imports) + "\n"
    if names:
        text += f"from {mod} import (\n" + "".join(f"    {n} as {n},\n" for n in names) + ")\n"
    text += '\n_T = TypeVar("_T", bound=np.generic)\n'
    text += "\n".join(body) + "\n"
    return text


def outputs() -> dict[Path, str]:
    out = {}
    for stub in sorted(PKG.rglob("*.pyi")):
        text = generate(stub)
        if text is not None:
            out[OUT / ("reveal_" + module_name(stub).replace(".", "_") + ".py")] = text
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed files differ")
    opts = ap.parse_args()
    want = outputs()
    if opts.check:
        bad = False
        have = {p for p in OUT.glob("*.py")} if OUT.exists() else set()
        for p, text in want.items():
            old = p.read_text() if p.exists() else ""
            if old != text:
                bad = True
                sys.stdout.writelines(difflib.unified_diff(old.splitlines(True), text.splitlines(True), str(p), "regenerated", n=1))
        for p in have - set(want):
            bad = True
            print(f"{p} has no stub any more")
        if bad:
            print("\ntests/typing/reveals/ is out of date with the stubs. Run: python tests/typing/gen_reveals.py")
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob("*.py"):
        if p not in want:
            p.unlink()
    for p, text in want.items():
        p.write_text(text)
    print(f"wrote {len(want)} files, {sum(t.count('reveal_type(') - 1 for t in want.values())} reveals")
    return 0


if __name__ == "__main__":
    sys.exit(main())
